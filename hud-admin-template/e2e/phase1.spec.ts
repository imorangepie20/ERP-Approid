    expect(trace.movements.content).toHaveLength(2)
    expect(trace.movements.content.map((m: { sourceType: string }) => m.sourceType).sort()).toEqual(['SHIPMENT', 'WORK_ORDER'])
    await expect(lotDialog.getByRole('link', { name: `WORK_ORDER · ${confirmation.workOrderNo}`, exact: true })).toBeVisible()
    await expect(lotDialog.getByRole('link', { name: `SHIPMENT · ${shipment.shipmentNo}`, exact: true })).toBeVisible()

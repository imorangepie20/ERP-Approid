    await lotDialog.getByRole('link', { name: `SHIPMENT · ${shipment.shipmentNo}`, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`/sales/shipments\\?keyword=${shipment.shipmentNo}$`))
    await expect(page.getByRole('row').filter({ has: page.getByText(shipment.shipmentNo, { exact: true }) })).toContainText('출하완료')
    // Read the same persisted documents through Spring analytics (no network mocks).
    await page.goto('/')
    await expect(page.getByLabel('조회 시작일', { exact: true })).toHaveCSS('background-color', 'rgb(14, 23, 38)')
    await expect(page.getByLabel('조회 품목', { exact: true })).toHaveCSS('color', 'rgb(255, 255, 255)')
